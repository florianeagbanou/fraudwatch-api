CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(30)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE account (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(20)    NOT NULL UNIQUE,
    owner_id       BIGINT         NOT NULL REFERENCES app_user (id),
    balance        NUMERIC(19, 2) NOT NULL,
    currency       VARCHAR(3)     NOT NULL,
    home_country   VARCHAR(2)     NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    version        BIGINT         NOT NULL DEFAULT 0
);

CREATE TABLE bank_transaction (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT         NOT NULL REFERENCES account (id),
    type       VARCHAR(20)    NOT NULL,
    amount     NUMERIC(19, 2) NOT NULL,
    merchant   VARCHAR(100),
    country    VARCHAR(2)     NOT NULL,
    status     VARCHAR(20)    NOT NULL,
    risk_score INT            NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_transaction_account_created ON bank_transaction (account_id, created_at);

-- One row per fraud rule that matched a transaction
CREATE TABLE transaction_rule_hit (
    transaction_id BIGINT       NOT NULL REFERENCES bank_transaction (id),
    code           VARCHAR(40)  NOT NULL,
    points         INT          NOT NULL,
    reason         VARCHAR(255) NOT NULL
);

CREATE TABLE fraud_alert (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id  BIGINT      NOT NULL UNIQUE REFERENCES bank_transaction (id),
    status          VARCHAR(20) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    reviewed_by     VARCHAR(30),
    reviewed_at     TIMESTAMP WITH TIME ZONE,
    resolution_note VARCHAR(500)
);

CREATE INDEX idx_alert_status ON fraud_alert (status);

CREATE TABLE audit_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor       VARCHAR(30) NOT NULL,
    action      VARCHAR(40) NOT NULL,
    details     VARCHAR(500)
);
